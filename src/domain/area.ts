export function isInsideArea({ lat, lon }: Coordinates): boolean {
  let inside = false;
  let [previousLon, previousLat] = AREA[AREA.length - 1] ?? [0, 0];
  for (const [pointLon, pointLat] of AREA) {
    const spans = pointLat > lat !== previousLat > lat;
    if (spans && lon < ((previousLon - pointLon) * (lat - pointLat)) / (previousLat - pointLat) + pointLon) {
      inside = !inside;
    }
    [previousLon, previousLat] = [pointLon, pointLat];
  }
  return inside;
}

/** Reads `lat,lon` as the form's hidden fields send it; anything else is no coordinates. */
export function parseCoordinates(text: string | null): Coordinates | undefined {
  const match = /^(-?\d{1,3}(?:\.\d+)?),(-?\d{1,3}(?:\.\d+)?)$/.exec(text ?? '');
  if (match === null) {
    return undefined;
  }
  const lat = Number(match[1]);
  const lon = Number(match[2]);
  return Math.abs(lat) <= 90 && Math.abs(lon) <= 180 ? { lat, lon } : undefined;
}
